"""Recognised password hashing configuration for core-backend (NFR-051).

Uses Django's built-in `Argon2PasswordHasher` (backed by `argon2-cffi`, Argon2id variant)
with explicitly documented OWASP-aligned cost parameters and a fresh cryptographic random
16-byte per-password salt.
"""

from django.contrib.auth.hashers import Argon2PasswordHasher


class CoreArgon2PasswordHasher(Argon2PasswordHasher):
    """Argon2id password hasher with explicitly documented parameters (NFR-051).

    Parameters (argon2id, v=19):
    - time_cost = 2 iterations
    - memory_cost = 19456 KiB (~19 MiB, OWASP Password Storage Cheat Sheet baseline for t=2, p=1)
    - parallelism = 1 lane
    - salt_len = 16 bytes (128-bit per-password random salt generated by argon2-cffi)
    - hash_len = 32 bytes (256-bit derived key)
    """

    time_cost = 2
    memory_cost = 19456
    parallelism = 1
